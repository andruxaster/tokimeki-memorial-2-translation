def capacity(p, off, n):
    e = off + n
    end = e
    while end < len(p) and p[end] == 0 and end - off < 80: end += 1
    end &= ~3
    return max(n, end - off - 1)

def patches(p):
    """p: pack bytes (unswapped). Returns (list of (off, bytes), warnings)."""
    wins = []
    for a in ANCHORS:
        for m in re.finditer(re.escape(a.encode('cp932')), p):
            wins.append((max(0, m.start() - WINDOW), m.start() + WINDOW))
    out = {}; warn = []
    for lo, hi in wins:
        seg = p[lo:hi]
        for jp, ru in list(UI.items()) + list(MID.items()):
            jb = jp.encode('cp932')
            for m in re.finditer(re.escape(jb), seg):
                off = lo + m.start()
                if off in out: continue
                nxt = p[off + len(jb)]
                if jp in MID:
                    if nxt not in (0, 10): continue
                else:
                    if (p[off - 1] not in (0, 10) and off % 4) or nxt not in (0, 10): continue
                if nxt == 10:        # line break follows: same length, blank-cell padding
                    rb = vwf.encode(ru)
                    if len(rb) > len(jb): warn.append('%x too long: %s' % (off, ru)); continue
                    out[off] = rb + vwf.cell_code(' ', ' ') * ((len(jb) - len(rb)) // 2); continue
                rb = vwf.encode(ru)
                if jp in OPTIONS:          # fixed-width fields: exact length, blank-cell padding
                    if len(rb) > len(jb): warn.append('%x too long: %s' % (off, ru)); continue
                    out[off] = rb + vwf.cell_code(' ', ' ') * ((len(jb) - len(rb)) // 2); continue
                cap = capacity(p, off, len(jb))
                if len(rb) > cap: warn.append('%x too long: %s' % (off, ru)); continue
                out[off] = rb + bytes(max(0, len(jb) - len(rb))) + (b'\0' if len(rb) > len(jb) else b'')
    return sorted(out.items()), warn

def patch_pack(img, p):
    ps, w = patches(p)
    for off, b in ps: img.write(img.pack_lba, off, b)
    return len(ps), w

