def capacity(ov, off, jb):
    """bytes usable for text (excluding the terminating zero)."""
    e = off + len(jb)
    assert ov[e] == 0
    while e + 1 < len(ov) and ov[e + 1] == 0 and (e + 1 - off) < 64: e += 1
    # stay before the next aligned non-zero data
    end = e + 1                      # first non-zero byte (or limit)
    end &= ~3                        # next data starts on a 4-byte boundary
    cap = max(len(jb), end - off - 1) & ~1
    if off >= 0x50000: cap = min(cap, 26)        # 32-byte location records
    return cap

def patches(ov):
    out, errs = [], []
    for a, (jp, ru) in sorted(UI.items()):
        off = a - OV; jb = jp.encode('cp932')
        if ov[off:off + len(jb)] != jb: errs.append('%x: mismatch' % a); continue
        cap = capacity(ov, off, jb)
        rb = vwf.encode(ru)
        if len(rb) > cap: errs.append('%x: too long %d>%d %s' % (a, len(rb), cap, ru)); continue
        out.append((off, rb + bytes(len(jb) + 1 - len(rb)) if len(rb) <= len(jb) else rb + b'\0'))
    return out, errs

